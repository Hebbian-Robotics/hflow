"""The runtime bundle's file templates, as plain Python string constants.

Templates live as ``string.Template`` constants rather than packaged data
files so the package stays wheel-simple (no ``package_data`` plumbing, no
resource loading). Two delimiter regimes keep escaping sane:

- :data:`COMPOSE_TEMPLATE` uses ``%``-placeholders (:class:`ComposeTemplate`)
  because the compose file is full of ``${VAR}`` interpolations that Docker
  Compose itself resolves from ``.env``, plus ``$$``-escaped shell variables
  in the embedded bash script -- a ``$`` delimiter would force ``$$$$``
  quadruple escaping.
- The DAG templates (:data:`MASTER_DAG_TEMPLATE` and the two sub-DAG
  templates) are standard ``$``-delimiter templates; the generated Python
  source contains no ``$``.

Every Airflow fact encoded here (service set, exact env var names, the
health endpoint, JWT auth, external-python constraints) is cited in
references/airflow3-notes.md.
"""

