# Injected into the media sub-DAG's plan (empty for other stages, and for
# BUCKET data roots -- reading a remote episode's channel list would download
# the whole file, which costs more than the skipped cycle saves): media
# derives per-camera artifacts, so camera-less episodes would pay a full
# plan -> map -> gate cycle (~10s measured 2026-08-18) to record nothing.
# When nothing in the run has cameras the plan exits 99, which
# skip_on_exit_code turns into a SKIPPED task (the UI shows the stage never
# applied, not a hollow success); downstream tasks skip with it.
MEDIA_PLAN_FILTER_TEMPLATE = Template(
    """\
        from pathlib import Path

        from hflow.format import CAMERA_SCHEMA_NAMES
        from hflow.reader import open_reader

        def has_camera(uri):
            reader = open_reader(Path("$data_root") / str(uri))
            try:
                return any(
                    info.schema_name in CAMERA_SCHEMA_NAMES
                    for info in reader.channels().values()
                )
            finally:
                reader.close()

        # Media applies only to camera-bearing episodes (see template note).
        uris = [uri for uri in uris if has_camera(uri)]
        if not uris:
            raise SystemExit(99)  # skip_on_exit_code: whole stage SKIPPED
"""
)
