# The master ingest DAG (the master half of the ingest stage graph), shared
# by the Compose runtime (render_bundle) and `hflow deploy`
# (render_deploy_bundle).
# Substitutions: $dag_id, the four $*_dag_id sub-DAG ids, and
# $run_profiles_literal -- a dict literal baked from hflow.steps.
# RUN_PROFILES at render time (steps.py stays the one owner of the profile
# vocabulary; the baked copy is generated code). The master runs ENTIRELY in
# Airflow's own environment: no external_python, no hflow import --
# TriggerDagRunOperator ships in apache-airflow-providers-standard, which the
# official image includes, and its deferrable wait needs the triggerer
# service, which every rendered runtime runs.
MASTER_DAG_TEMPLATE = Template(
    '''\
"""Master ingest DAG "$dag_id" -- generated by hflow; re-render instead of editing.

The master half of the ingest stage graph: resolve the run profile to its
enabled stage set, then trigger only those sub-DAGs, chained sequentially
(sync >> meta >> labels >> media). Runs entirely in Airflow's own environment
-- no user venv, no hflow import.

Trigger conf: {"uris": [...], "profile": "full", "mode": "batch"|"online",
"batch_count": optional int, "all_stages": optional bool}.
"uris"/"mode"/"batch_count"/"all_stages" pass through to
every triggered sub-DAG; mode "online" is the latency-first lane (one run per
episode as it lands): each sub-DAG processes the conf's uris as one immediate
batch, no bin-packing, no stagger.

How the stage graph's profile toggles map onto tasks: the profile arrives in
the run conf, so which stages run cannot be a parse-time conditional. Instead every
stage's trigger always exists behind its own enabled_<stage> gate task, and a
gate raises AirflowSkipException when the resolved profile disables its stage
-- the skip cascades to exactly that stage's trigger (default all_success
rule), while the next gate's trigger_rule="none_failed" lets it run after
skipped (but never failed) predecessors. So the enabled sub-DAGs execute
strictly in sequence, a disabled stage shows as two skipped tasks in the UI,
and a failed sub-DAG still stops the chain. Deliberately NOT a @task.branch:
skip_all_except treats everything downstream of a followed branch as also
followed, and with the triggers chained sequentially that would silently
re-enable every stage after the first enabled one (a "labels"-only profile
would run media too).
"""

from airflow.providers.standard.operators.trigger_dagrun import TriggerDagRunOperator
from airflow.sdk import dag, task

# Baked from hflow.steps.RUN_PROFILES and hflow.steps.IngestMode at render
# time -- re-render after changing either; never edit these literals by hand.
RUN_PROFILE_STAGES = $run_profiles_literal
VALID_INGEST_MODES = $ingest_modes_literal

# Declaration order is the stage graph's execution order.
STAGE_SUB_DAG_IDS = {
    "sync": "$sync_dag_id",
    "meta": "$meta_dag_id",
    "labels": "$labels_dag_id",
    "media": "$media_dag_id",
}

# Rendered on the DAG's page in the Airflow UI (the profile table is baked
# from hflow.steps.RUN_PROFILES at render time, like the literal above).
DOC_MD = """\
## Master ingest -- resolves the run profile, triggers only the sub-DAGs it needs

The master half of the ingest stage graph. Enabled stages run strictly in
order (sync >> meta >> labels >> media); a stage disabled by the profile shows as
two **skipped** tasks, and a teal **deferred** trigger task is intentionally
waiting on its sub-DAG run to finish.

| run profile | stages enabled |
|---|---|
$profile_table_rows

**Trigger conf** -- `uris`: episode files relative to the data root;
`profile`: a row above (default `full`); `mode`: `batch` bin-packs uris into
staggered near-equal-byte shards, `online` is the latency-first lane (one
immediate run, no batching, no stagger); `batch_count`: optional override;
`all_stages`: run every stage over everything it is handed instead of only
what the catalog does not already record as current.

Each sub-DAG (`$sync_dag_id`, `$meta_dag_id`, `$labels_dag_id`,
`$media_dag_id`) is also directly triggerable with the same conf for
per-stage reruns -- e.g. a re-label pass over already-canonical episodes.
"""


@dag(
    dag_id="$dag_id",
    dag_display_name="$master_display_name",
    description="Resolves the run profile and triggers only the enabled stage sub-DAGs.",
    doc_md=DOC_MD,
    tags=["$pipeline_tag", "master"],
    schedule=None,
    render_template_as_native_obj=True,
    params={
        "uris": [],
        "profile": "full",
        "mode": "batch",
        "batch_count": None,
        "all_stages": False,
    },
)
def master_ingest():
    @task
    def resolve_profile(profile, mode):
        """Validate the conf against the baked vocabulary; return the enabled stages."""
        if profile not in RUN_PROFILE_STAGES:
            raise ValueError(
                f"unknown run profile {profile!r}; valid profiles: "
                f"{sorted(RUN_PROFILE_STAGES)}"
            )
        if mode not in VALID_INGEST_MODES:
            raise ValueError(
                f"unknown mode {mode!r}; valid modes: {', '.join(VALID_INGEST_MODES)}"
            )
        return list(RUN_PROFILE_STAGES[profile])

    @task(trigger_rule="none_failed")
    def stage_gate(stage_name, enabled_stage_names):
        """Skip this stage's trigger when the profile disables it (a stage toggle)."""
        from airflow.exceptions import AirflowSkipException

        if stage_name not in enabled_stage_names:
            raise AirflowSkipException(
                f"stage {stage_name!r} disabled by the run profile "
                f"(enabled: {enabled_stage_names})"
            )

    enabled_stage_names = resolve_profile(
        profile="{{ params.profile }}", mode="{{ params.mode }}"
    )

    previous_trigger = None
    for stage_name, sub_dag_id in STAGE_SUB_DAG_IDS.items():
        gate = stage_gate.override(task_id=f"enabled_{stage_name}")(
            stage_name, enabled_stage_names
        )
        trigger = TriggerDagRunOperator(
            task_id=f"trigger_{stage_name}",
            # A teal "deferred" state reads as stalled to demo audiences;
            # the display name and doc say the wait is intentional.
            task_display_name=f"trigger {stage_name} · waits (deferred)",
            doc_md=(
                f"Triggers `{sub_dag_id}` and waits (deferred, checked every "
                "5s) for that run to finish before the next stage's gate."
            ),
            trigger_dag_id=sub_dag_id,
            conf={
                "uris": "{{ params.uris }}",
                "mode": "{{ params.mode }}",
                "batch_count": "{{ params.batch_count }}",
                "all_stages": "{{ params.all_stages }}",
            },
            wait_for_completion=True,
            deferrable=True,
            # Measured (2026-08-18): the deferral wait wastes ~poke_interval/2
            # per hop after a sub-DAG finishes; at local run volumes a 2s poll
            # costs the triggerer nothing and saves ~1.5s per stage hop.
            poke_interval=2,
        )
        gate >> trigger
        if previous_trigger is not None:
            previous_trigger >> gate
        previous_trigger = trigger


master_ingest()
'''
)


# The sub-DAG templates (the stage graph's four toggleable sub-DAGs), shared
# by the Compose runtime and `hflow deploy`. Substitutions: $dag_id,
# $master_dag_id, $stage_title, $stage_name, $gate_name, $pipeline_filename,
# $app_variable, plus the two facts the deployments disagree on -- $data_root
# (where episode URIs resolve inside the task processes) and $venv_python
# (the user venv's interpreter). Every task runs via @task.external_python
# against the user venv, so ALL imports live inside the function bodies (the
# operator extracts each body to a temp file; module globals do not survive)
# and everything passed between tasks is plain JSON-able data. The two
# variants differ only in the gate: checks decide quarantine, so the
# quarantine budget lives ONLY in the meta sub-DAG; every other stage keeps
# the error-budget half.
_SUB_DAG_HEADER = '''\
"""$stage_title sub-DAG "$dag_id" -- generated by hflow; re-render instead of editing.

One of the ingest stage graph's four toggleable sub-DAGs, normally triggered
by the master DAG "$master_dag_id" (direct triggering with the same conf also
works).
plan -> process_batch (dynamically mapped) -> $gate_name, all via
@task.external_python against the user venv at $venv_python_doc (user dependencies
never meet Airflow's pins). Imports live inside the function bodies because
the operator extracts each body to a temp file; only JSON-able data crosses
task borders. Trigger conf: {"uris": [...], "mode": "batch"|"online",
"batch_count": optional int, "all_stages": optional bool}.
"""

from airflow.sdk import dag, task

# Rendered on the DAG's page in the Airflow UI.
DOC_MD = """\
## $stage_title -- stage sub-DAG

$stage_description

Normally triggered by the master DAG `$master_dag_id` (its run profile
decides which stages run); triggering it directly with the same conf
also works, for per-stage reruns. Tasks execute in the isolated user venv --
user dependencies never meet Airflow's pins.

**Trigger conf** -- `uris`: episode files relative to the data root;
`mode`: `batch` (bin-packed, staggered shards) or `online` (one immediate
latency-first run); `batch_count`: optional override; `all_stages`: run every
uri handed over instead of only the ones this stage still owes work on.
"""


@dag(
    dag_id="$dag_id",
    dag_display_name="$sub_display_name",
    description="$stage_description",
    doc_md=DOC_MD,
    tags=["$pipeline_tag", "stage:$stage_name"],
    schedule=None,
    render_template_as_native_obj=True,
    params={"uris": [], "mode": "batch", "batch_count": None, "all_stages": False},
)
def ingest_stage():
    @task.external_python(python=$venv_python, expect_airflow=False, skip_on_exit_code=99$task_queue_argument)
    def plan(uris, mode, batch_count, all_stages):
        """Narrow uris to what this stage still owes, then bin-pack them.

        The lane semantics live in hflow.stage_execution (one owner for every
        execution backend); this task only feeds it the trigger conf. Any
        narrowing happens first, so the bin-packer only ever sees work that
        is going to run.

        all_stages is the conf escape hatch: true runs every uri handed over,
        whatever the catalog already records. It is the scheduled counterpart
        of `hflow ingest --all-stages`, and exists for the one thing the
        catalog cannot see -- an artifact deleted out from under a step whose
        rows still say it ran.
        """
        from hflow.stage_execution import plan_stage_batches

        if not uris:
            return []
        # Conf values arrive rendered; a native bool passes straight through
        # and a hand-typed string is read the way every other flag in the
        # project reads one.
        if isinstance(all_stages, str):
            all_stages = all_stages.strip().lower() in {"1", "true", "yes", "on"}
$stage_plan_filter        return plan_stage_batches(
            [str(uri) for uri in uris],
            mode=mode,
            batch_count=batch_count,
            data_root=$data_root,
        )

    @task.external_python(python=$venv_python, expect_airflow=False$task_queue_argument)
    def process_batch(batch, orchestrator_run_id):
        """Sleep the stagger delay, then run this sub-DAG's stage on every episode.

        The pipeline-loading contract and the per-episode accounting loop live
        in hflow.stage_execution; this task binds them to the rendered
        data root and pipeline file.

        orchestrator_run_id arrives as a rendered template argument, not from the
        Airflow context: expect_airflow=False means Airflow is not importable
        in the user venv this runs in, so the run id has to be handed over
        from the DAG side. It is recorded on every episode the batch appends.
        """
        import os
        import time

        from hflow.app import DATA_ROOT_ENVIRONMENT_VARIABLE
        from hflow.stage_execution import (
            load_pipeline_application,
            process_stage_batch,
            require_application_data_root,
            resolve_user_pipeline_path,
        )

        time.sleep(float(batch["start_delay_s"]))

        expected_data_root = $data_root
        # Environment-portable pipelines (App constructed without an explicit
        # data_root) resolve their root from this variable; a pipeline that
        # hardcodes a different literal is refused by the guard below.
        os.environ[DATA_ROOT_ENVIRONMENT_VARIABLE] = expected_data_root
        pipeline_path = resolve_user_pipeline_path($pipeline_filename)
        app = load_pipeline_application(pipeline_path, "$app_variable")
        require_application_data_root(app, expected_data_root)
        return process_stage_batch(app, batch["items"], "$stage_name", orchestrator_run_id)
'''

